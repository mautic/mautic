<?php

namespace Mautic\LeadBundle\Form\Type;

use Mautic\CategoryBundle\Form\Type\CategoryListType;
use Mautic\CoreBundle\Form\EventListener\CleanFormSubscriber;
use Mautic\CoreBundle\Form\EventListener\FormExitSubscriber;
use Mautic\CoreBundle\Form\Type\FormButtonsType;
use Mautic\CoreBundle\Form\Type\YesNoButtonGroupType;
use Mautic\CoreBundle\Form\Validator\Constraints\CircularDependency;
use Mautic\LeadBundle\Entity\LeadList;
use Mautic\LeadBundle\Form\DataTransformer\FieldFilterTransformer;
use Mautic\LeadBundle\Model\ListModel;
use Mautic\LeadBundle\Provider\TypeOperatorProviderInterface;
use Mautic\LeadBundle\Segment\RelativeDate;
use Mautic\LeadBundle\Validator\Constraints\SegmentDate;
use Mautic\ProjectBundle\Form\Type\ProjectType;
use Symfony\Component\Form\AbstractType;
use Symfony\Component\Form\Extension\Core\Type\CollectionType;
use Symfony\Component\Form\Extension\Core\Type\HiddenType;
use Symfony\Component\Form\Extension\Core\Type\TextareaType;
use Symfony\Component\Form\Extension\Core\Type\TextType;
use Symfony\Component\Form\FormBuilderInterface;
use Symfony\Component\Form\FormEvents;
use Symfony\Component\Form\FormInterface;
use Symfony\Component\Form\FormView;
use Symfony\Component\OptionsResolver\OptionsResolver;
use Symfony\Component\Validator\Constraints as Assert;
use Symfony\Component\Validator\Context\ExecutionContextInterface;
use Symfony\Contracts\Translation\TranslatorInterface;

/**
 * @extends AbstractType<LeadList>
 */
final class ListType extends AbstractType
{
    public function __construct(
        private readonly TranslatorInterface $translator,
        private readonly ListModel $listModel,
        private readonly RelativeDate $relativeDate,
        TypeOperatorProviderInterface $typeOperatorProvider,
    ) {
        $typeOperatorProvider->setContext('segment');
    }

    public function buildForm(FormBuilderInterface $builder, array $options): void
    {
        $builder->addEventSubscriber(new CleanFormSubscriber(['description' => 'html', 'name' => 'string', 'publicName' => 'string', 'filter' => 'raw']));
        $builder->addEventSubscriber(new FormExitSubscriber('lead.list', $options));
        $builder->addEventListener(FormEvents::PRE_SUBMIT, static function ($event): void {
            $data = $event->getData();
            if (is_array($data) && '0' === (string) ($data['isPreferenceCenter'] ?? '')) {
                unset($data['translations']);
                $event->setData($data);
            }
        });

        $builder->add(
            'name',
            TextType::class,
            [
                'label'      => 'mautic.core.name',
                'label_attr' => ['class' => 'form-label'],
                'attr'       => ['class' => 'form-control'],
            ]
        );

        $builder->add(
            'publicName',
            TextType::class,
            [
                'label'      => 'mautic.lead.list.form.publicname',
                'label_attr' => ['class' => 'form-label'],
                'attr'       => [
                    'class'       => 'form-control',
                    'tooltip'     => 'mautic.lead.list.form.publicname.tooltip',
                    'placeholder' => 'mautic.core.autogenerated',
                ],
                'required' => false,
            ]
        );

        $builder->add(
            'alias',
            TextType::class,
            [
                'label'      => 'mautic.core.alias',
                'label_attr' => ['class' => 'form-label'],
                'attr'       => [
                    'class'       => 'form-control',
                    'length'      => 25,
                    'tooltip'     => 'mautic.lead.list.help.alias',
                    'placeholder' => 'mautic.core.autogenerated',
                ],
                'required' => false,
            ]
        );

        $builder->add(
            'description',
            TextareaType::class,
            [
                'label'      => 'mautic.core.description',
                'label_attr' => ['class' => 'form-label'],
                'attr'       => ['class' => 'form-control editor'],
                'required'   => false,
            ]
        );

        $builder->add(
            'category',
            CategoryListType::class,
            [
                'bundle' => 'segment',
            ]
        );

        $builder->add(
            'isGlobal',
            YesNoButtonGroupType::class,
            [
                'label'      => 'mautic.lead.list.form.isglobal',
                'attr'       => [
                    'tooltip' => 'mautic.lead.list.form.isglobal.tooltip',
                ],
                'no_label'   => 'mautic.lead.list.form.isglobal.no',
            ]
        );

        $builder->add(
            'isPreferenceCenter',
            YesNoButtonGroupType::class,
            [
                'label'      => 'mautic.lead.list.form.isPreferenceCenter',
                'attr'       => [
                    'tooltip' => 'mautic.lead.list.form.isPreferenceCenter.tooltip',
                ],
            ]
        );

        $builder->add('projects', ProjectType::class);
        $builder->add('isPublished', YesNoButtonGroupType::class);

        $builder->add('translationsSubmitted', HiddenType::class, [
            'mapped' => false,
            'data'   => '1',
        ]);
        $builder->add('translations', CollectionType::class, [
            'entry_type'     => LeadListTranslationType::class,
            'mapped'         => false,
            'data'           => $options['translation_rows'],
            'allow_add'      => true,
            'allow_delete'   => true,
            'error_bubbling' => false,
            'label'          => false,
            'constraints'    => [new Assert\Callback($this->validateTranslationLocales(...))],
        ]);

        $filterModalTransformer = new FieldFilterTransformer($this->translator, $this->relativeDate, ['object' => 'lead']);
        $builder->add(
            $builder->create(
                'filters',
                CollectionType::class,
                [
                    'entry_type'     => FilterType::class,
                    'error_bubbling' => false,
                    'mapped'         => true,
                    'allow_add'      => true,
                    'allow_delete'   => true,
                    'label'          => false,
                    'constraints'    => [
                        new CircularDependency(message: 'mautic.core.segment.circular_dependency_exists'),
                        new SegmentDate(message: 'mautic.lead.segment.date_invalid'),
                    ],
                ]
            )->addModelTransformer($filterModalTransformer)
        );

        $builder->add('buttons', FormButtonsType::class);

        if (!empty($options['action'])) {
            $builder->setAction($options['action']);
        }
    }

    public function configureOptions(OptionsResolver $resolver): void
    {
        $resolver->setDefaults(
            [
                'data_class' => LeadList::class,
                'translation_rows' => [],
            ]
        );
    }

    public function buildView(FormView $view, FormInterface $form, array $options): void
    {
        $view->vars['fields'] = $this->listModel->getChoiceFields();
    }

    public function getBlockPrefix(): string
    {
        return 'leadlist';
    }

    public function validateTranslationLocales(mixed $rows, ExecutionContextInterface $context): void
    {
        if (!is_array($rows)) {
            return;
        }

        $seen = [];
        foreach ($rows as $index => $row) {
            if (!is_array($row) || empty($row['locale'])) {
                continue;
            }

            $locale = str_replace('-', '_', (string) $row['locale']);
            if (isset($seen[$locale])) {
                $context->buildViolation($this->translator->trans('mautic.lead.list.translation.duplicate_locale'))
                    ->atPath('['.$index.'].locale')
                    ->addViolation();
            }
            $seen[$locale] = true;
        }
    }
}
