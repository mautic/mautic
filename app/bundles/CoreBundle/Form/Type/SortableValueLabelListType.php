<?php

namespace Mautic\CoreBundle\Form\Type;

use Mautic\CoreBundle\Helper\InputHelper;
use Symfony\Component\Form\AbstractType;
use Symfony\Component\Form\Extension\Core\Type\TextType;
use Symfony\Component\Form\FormBuilderInterface;
use Symfony\Component\Form\FormEvent;
use Symfony\Component\Form\FormEvents;
use Symfony\Component\Form\FormInterface;
use Symfony\Component\Form\FormView;
use Symfony\Component\OptionsResolver\OptionsResolver;

/**
 * @extends AbstractType<mixed>
 */
final class SortableValueLabelListType extends AbstractType
{
    private const LABEL_PLACEHOLDER = 'mautic.core.label';

    private const VALUE_PLACEHOLDER = 'mautic.core.value_autogenerated';

    public function buildForm(FormBuilderInterface $builder, array $options): void
    {
        $builder->add(
            'label',
            TextType::class,
            [
                'label'          => $options['label_placeholder'] ?? self::LABEL_PLACEHOLDER,
                'error_bubbling' => true,
                'attr'           => ['class' => 'form-control'],
                'constraints'    => $options['label_constraints'] ?? [],
            ]
        );

        $builder->add(
            'value',
            TextType::class,
            [
                'label'          => $options['value_placeholder'] ?? self::VALUE_PLACEHOLDER,
                'error_bubbling' => true,
                'required'       => false,
                'attr'           => ['class' => 'form-control'],
                'constraints'    => $options['value_constraints'] ?? [],
            ]
        );

        if (!($options['generate_value'] ?? true)) {
            return;
        }

        $builder->addEventListener(
            FormEvents::PRE_SUBMIT,
            function (FormEvent $event): void {
                $data = $event->getData();

                if (is_array($data)
                    && (!isset($data['value']) || '' === $data['value'])
                    && !empty($data['label'])
                ) {
                    $data['value'] = $this->generateSlugFromLabel((string) $data['label']);
                    $event->setData($data);
                }
            }
        );
    }

    public function configureOptions(OptionsResolver $resolver): void
    {
        $resolver->setDefaults(
            [
                'label_placeholder' => self::LABEL_PLACEHOLDER,
                'value_placeholder' => self::VALUE_PLACEHOLDER,
                // Fills an empty value from the label, as for the options of a select field
                'generate_value'    => true,
                'label_constraints' => [],
                'value_constraints' => [],
            ]
        );
    }

    public function buildView(FormView $view, FormInterface $form, array $options): void
    {
        parent::buildView($view, $form, $options);

        $view->vars['preaddonAttr']  = $options['attr']['preaddon_attr'] ?? [];
        $view->vars['postaddonAttr'] = $options['attr']['postaddon_attr'] ?? [];
        $view->vars['preaddon']      = $options['attr']['preaddon'] ?? [];
        $view->vars['postaddon']     = $options['attr']['postaddon'] ?? [];
    }

    private function generateSlugFromLabel(string $label): string
    {
        $transliterated = InputHelper::transliterate($label);
        if (false === $transliterated) {
            return '';
        }
        $alphanumeric = InputHelper::alphanum($transliterated, false, '_');
        $trimmed      = trim($alphanumeric, '_');
        $normalized   = preg_replace('/_+/', '_', $trimmed);

        return strtolower($normalized ?? '');
    }
}
